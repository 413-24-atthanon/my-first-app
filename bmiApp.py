import streamlit as st

# ส่วนที่ 1 หัวข้อหน้าเว็บ (Title สีแดง)
st.markdown("# :red[🏋️ คำนวณค่าดัชนีมวลกาย BMI]")
st.write("กรอกข้อมูลน้ำหนักและส่วนสูงของคุณ เพื่อเช็กสุขภาพเบื้องต้น")

# ส่วนที่ 2 สร้างช่องรับค่าน้ำหนัก และ ส่วนสูง
weight = st.number_input("กรอกน้ำหนักของคุณ (กิโลกรัม):", min_value=1.0)
height_cm = st.number_input("กรอกส่วนสูงของคุณ (เซนติเมตร):", min_value=1.0)

# ส่วนที่ 3 คำนวณค่า BMI และแสดงผลลัพธ์
if st.button("คำนวณ BMI"):
    # แปลงส่วนสูงจากเซนติเมตรเป็นเมตร
    height_m = height_cm / 100
    
    # คำนวณค่า BMI (น้ำหนัก หารด้วย ส่วนสูงยกกำลังสอง)
    bmi = weight / (height_m ** 2)
    
    # แสดงค่า BMI แบบทศนิยม 2 ตำแหน่ง
    st.success(f"ค่า BMI ของคุณคือ: {bmi:.2f}")
    
    # ประเมินผลตามเกณฑ์สุขภาพ
    if bmi < 18.5:
        st.warning("น้ำหนักน้อย / ผอม")
    elif 18.5 <= bmi < 23.0:
        st.info("น้ำหนักปกติ / สุขภาพดี")
    elif 23.0 <= bmi < 25.0:
        st.warning("น้ำหนักเกิน / อ้วนระดับ 1")
    elif 25.0 <= bmi < 30.0:
        st.error("อ้วน / อ้วนระดับ 2")
    else:
        st.error("อ้วนมาก / อ้วนระดับ 3")
