import time
import streamlit as st

st.title("🇹🇭 เกมทายจังหวัดในประเทศไทย")
st.write("🎯 ทายชื่อจังหวัดจากคำใบ้ให้ถูกต้องภายในเวลาที่กำหนด")


# ====================================================
# 1. กำหนดค่าเริ่มต้นใน session_state
# ====================================================

if "ans1_val" not in st.session_state:
    st.session_state.ans1_val = ""

if "ans2_val" not in st.session_state:
    st.session_state.ans2_val = ""

if "ans3_val" not in st.session_state:
    st.session_state.ans3_val = ""

if "ans4_val" not in st.session_state:
    st.session_state.ans4_val = ""

if "ans5_val" not in st.session_state:
    st.session_state.ans5_val = ""

if "is_ended" not in st.session_state:
    st.session_state.is_ended = False


# ====================================================
# 2. ฟังก์ชันเริ่มเกมใหม่
# ====================================================

def reset_game():

    st.session_state.ans1_val = ""
    st.session_state.ans2_val = ""
    st.session_state.ans3_val = ""
    st.session_state.ans4_val = ""
    st.session_state.ans5_val = ""

    # เริ่มจับเวลา
    st.session_state.start = time.time()

    # เกมยังไม่จบ
    st.session_state.is_ended = False


# ====================================================
# 3. ฟังก์ชันแสดงผลคะแนน
# ====================================================

@st.dialog("📊 สรุปผลการเล่นเกม")
def show_result_dialog(ans1, ans2, ans3, ans4, ans5):

    score = 0

    # ทำให้ตัวพิมพ์เล็ก/ใหญ่ไม่มีผล
    u_ans1 = ans1.strip().lower()
    u_ans2 = ans2.strip().lower()
    u_ans3 = ans3.strip().lower()
    u_ans4 = ans4.strip().lower()
    u_ans5 = ans5.strip().lower()


    # ====================================================
    # ตรวจข้อ 1
    # ====================================================

    if u_ans1 == "เชียงใหม่":
        st.success("✅ ข้อ 1: ถูกต้อง")
        score += 1
    else:
        st.error(
            f"❌ ข้อ 1: ยังไม่ถูกต้อง "
            f"(คุณตอบ '{u_ans1}')"
        )


    # ====================================================
    # ตรวจข้อ 2
    # ====================================================

    if u_ans2 == "ภูเก็ต":
        st.success("✅ ข้อ 2: ถูกต้อง")
        score += 1
    else:
        st.error(
            f"❌ ข้อ 2: ยังไม่ถูกต้อง "
            f"(คุณตอบ '{u_ans2}')"
        )


    # ====================================================
    # ตรวจข้อ 3
    # ====================================================

    if u_ans3 == "นครราชสีมา":
        st.success("✅ ข้อ 3: ถูกต้อง")
        score += 1
    else:
        st.error(
            f"❌ ข้อ 3: ยังไม่ถูกต้อง "
            f"(คุณตอบ '{u_ans3}')"
        )


    # ====================================================
    # ตรวจข้อ 4
    # ====================================================

    if u_ans4 == "กาญจนบุรี":
        st.success("✅ ข้อ 4: ถูกต้อง")
        score += 1
    else:
        st.error(
            f"❌ ข้อ 4: ยังไม่ถูกต้อง "
            f"(คุณตอบ '{u_ans4}')"
        )


    # ====================================================
    # ตรวจข้อ 5
    # ====================================================

    if u_ans5 == "ชลบุรี":
        st.success("✅ ข้อ 5: ถูกต้อง")
        score += 1
    else:
        st.error(
            f"❌ ข้อ 5: ยังไม่ถูกต้อง "
            f"(คุณตอบ '{u_ans5}')"
        )


    # ====================================================
    # แสดงคะแนนรวม
    # ====================================================

    st.info(f"🏆 คะแนนรวม: {score} / 5 คะแนน")


    # ====================================================
    # ใช้ if-else ตัดสินผล
    # ====================================================

    if score == 5:

        st.success("🎉 ยอดเยี่ยม! คุณตอบถูกทุกข้อ!")

    elif score >= 3:

        st.warning("👍 ทำได้ดี! คุณผ่านระดับการเล่นเกม")

    elif score >= 1:

        st.warning("💪 พยายามอีกนิดนะ!")

    else:

        st.error("💀 ยังไม่ถูกสักข้อ ลองเล่นใหม่อีกครั้ง!")


# ====================================================
# 4. ปุ่มเริ่มเกม
# ====================================================

st.button(
    "🎮 เริ่มเล่นเกม",
    on_click=reset_game
)


# ====================================================
# 5. ระบบจับเวลา
# ====================================================

if "start" in st.session_state and not st.session_state.is_ended:

    # กำหนดเวลา 30 วินาที
    time_left = int(
        30 - (time.time() - st.session_state.start)
    )


    if time_left > 0:

        st.error(
            f"⏳ เหลือเวลา: {time_left} วินาที"
        )

    else:

        st.session_state.is_ended = True

        st.rerun()


st.divider()


# ====================================================
# 6. คำถามข้อ 1
# ====================================================

ans1 = st.text_input(
    "ข้อ 1: จังหวัดใดอยู่ทางภาคเหนือ และมีดอยอินทนนท์ "
    "ซึ่งเป็นยอดเขาที่สูงที่สุดในประเทศไทย? 🏔️",
    value=st.session_state.ans1_val
)


# ====================================================
# 7. คำถามข้อ 2
# ====================================================

ans2 = st.text_input(
    "ข้อ 2: จังหวัดใดเป็นแหล่งท่องเที่ยวทางทะเลชื่อดัง "
    "และมีหาดป่าตอง? 🏝️",
    value=st.session_state.ans2_val
)


# ====================================================
# 8. คำถามข้อ 3
# ====================================================

ans3 = st.text_input(
    "ข้อ 3: จังหวัดใดมีพื้นที่ขนาดใหญ่ที่สุดในประเทศไทย "
    "และมีอนุสาวรีย์ท้าวสุรนารี? 🏛️",
    value=st.session_state.ans3_val
)


# ====================================================
# 9. คำถามข้อ 4
# ====================================================

ans4 = st.text_input(
    "ข้อ 4: จังหวัดใดมีสะพานข้ามแม่น้ำแคว "
    "และเป็นสถานที่สำคัญทางประวัติศาสตร์ในช่วงสงครามโลกครั้งที่ 2? 🌉",
    value=st.session_state.ans4_val
)


# ====================================================
# 10. คำถามข้อ 5
# ====================================================

ans5 = st.text_input(
    "ข้อ 5: จังหวัดใดเป็นจังหวัดท่องเที่ยวชายทะเล "
    "และมีสถานที่ท่องเที่ยวชื่อพัทยา? 🌊",
    value=st.session_state.ans5_val
)


# ====================================================
# 11. บันทึกคำตอบล่าสุด
# ====================================================

st.session_state.ans1_val = ans1
st.session_state.ans2_val = ans2
st.session_state.ans3_val = ans3
st.session_state.ans4_val = ans4
st.session_state.ans5_val = ans5


# ====================================================
# 12. ปุ่มส่งคำตอบ
# ====================================================

if "start" in st.session_state and not st.session_state.is_ended:

    if st.button("📥 ส่งคำตอบ"):

        st.session_state.is_ended = True

        st.rerun()


    # ทำให้เวลานับถอยหลัง
    time.sleep(1)

    st.rerun()


# ====================================================
# 13. แสดง Dialog เมื่อจบเกม
# ====================================================

if st.session_state.is_ended:

    show_result_dialog(

        st.session_state.ans1_val,
        st.session_state.ans2_val,
        st.session_state.ans3_val,
        st.session_state.ans4_val,
        st.session_state.ans5_val
    )
